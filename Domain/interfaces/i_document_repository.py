from typing import Protocol


class IDocumentRepository(Protocol):
    def documents(self) -> list[dict]: ...
    def document(self, document_id: str) -> dict | None: ...
    def save_document(self, document_id: str, **values) -> None: ...
    def save_answer(self, values: dict) -> dict: ...
    def answers(self, status: str | None = None, offset: int = 0) -> list[dict]: ...
    def review(self, answer_id: str, decision: str, reviewer: str, note: str) -> dict: ...
